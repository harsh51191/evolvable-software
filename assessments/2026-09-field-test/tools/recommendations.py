#!/usr/bin/env python3
"""Write recommendations.md for every field-test product, and a summary across them.

Each file is the skill's scripts/recommend.py output for the product's assessment, with a short note
written by a person after reading the evidence. Re-run after any assessment changes.
"""

import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, os.path.join(ROOT, "..", "..", "skills", "evolvable-software", "scripts"))

import recommend  # noqa: E402

NOTES = json.load(open(os.path.join(HERE, "recommendation-notes.json"), encoding="utf-8"))


def main():
    rows = []
    for name in sorted(os.listdir(ROOT)):
        path = os.path.join(ROOT, name, "assessment.json")
        if not os.path.isfile(path):
            continue
        rec, plain = recommend.make(path)
        text = recommend.render(rec, plain)
        head, _, rest = text.partition("\n\n")
        note = NOTES.get(name)
        if note:
            text = f"{head}\n\n**Do this first.** {note}\n\n{rest}"
        with open(os.path.join(ROOT, name, "recommendations.md"), "w", encoding="utf-8") as handle:
            handle.write(text)
        reach = "yes" if rec["level_after"] >= rec["next"] else f"no, {len(rec['rest'])} more steps"
        rows.append(f"| [{rec['product']}]({name}/recommendations.md) | {rec['level']} → {rec['next']} | "
                    + " | ".join(m["title"] for m in rec["moves"]) + f" | {reach} |")
    summary = [
        "# Next moves for the eleven products",
        "",
        "Generated by `tools/recommendations.py` from each assessment with the skill's `scripts/recommend.py`. "
        "Each product gets exactly three moves: one for the people running it, one for its improvement loop, "
        "one for safety. Whether they reach the next level is checked by re-running the scorer with the moves "
        "landed. Every move must ship on in the standard installation. Advice only: no score changes until a "
        "fresh assessment finds the work.",
        "",
        "| Product | Level now → next | 1. For the people running it | 2. For the loop | 3. For safety | Three moves reach the next level? |",
        "|---|---|---|---|---|---|",
        *rows,
        "",
    ]
    with open(os.path.join(ROOT, "recommendations.md"), "w", encoding="utf-8") as handle:
        handle.write("\n".join(summary))


if __name__ == "__main__":
    main()
